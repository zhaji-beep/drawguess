/* ==================================================================
 *  摊平 + 统计
 * ================================================================== */
const CATEGORIES = Object.keys(BANK);
const DIFF_ORDER = [1, 2, 3];

const WORDS = [];
for (const cat of CATEGORIES) {
  const tiers = BANK[cat] || {};
  for (const d of DIFF_ORDER) {
    for (const w of tiers[d] || []) WORDS.push([w, cat, d]);
  }
}

const DIFF_NAME = { 1: '简单', 2: '中等', 3: '困难' };

const byCategory = {};
const byDiff = { 1: 0, 2: 0, 3: 0 };
for (const w of WORDS) {
  byCategory[w[1]] = (byCategory[w[1]] || 0) + 1;
  byDiff[w[2]]++;
}

const WORD_STATS = {
  total: WORDS.length,
  categories: CATEGORIES.length,
  byCategory,
  byDiff
};

/** 每个分类下的词数（前端大厅展示用） */
const CATEGORY_META = CATEGORIES.map((c) => ({ name: c, count: byCategory[c] || 0 }));

/** 启动自检：同库内出现重词会打印告警，方便后续继续加词时不踩坑 */
function selfCheck(logger) {
  const seen = new Map();
  const dup = [];
  for (const w of WORDS) {
    if (seen.has(w[0])) dup.push(w[0] + '（' + seen.get(w[0]) + ' / ' + w[1] + '）');
    else seen.set(w[0], w[1]);
  }
  if (dup.length && logger) logger('[词库] 发现重复词：' + dup.join('、'));
  return dup;
}

module.exports = { BANK, WORDS, CATEGORIES, CATEGORY_META, WORD_STATS, DIFF_NAME, selfCheck };
